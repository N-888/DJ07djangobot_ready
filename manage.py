#!/usr/bin/env python
# Импортируем модуль os, чтобы работать с переменными окружения и путями запуска.
import os
# Импортируем модуль sys, чтобы передать Django аргументы командной строки.
import sys


# Создаем главную функцию, которая будет запускать административные команды Django.
def main() -> None:
    # Указываем Django, какой файл настроек использовать по умолчанию.
    os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'djangobot.settings')

    # Пробуем импортировать функцию запуска командной строки Django.
    try:
        # Импортируем стандартный исполнитель команд Django.
        from django.core.management import execute_from_command_line
    # Перехватываем ошибку, если Django еще не установлен в виртуальном окружении.
    except ImportError as exc:
        # Выбрасываем понятную ошибку с подсказкой для пользователя.
        raise ImportError(
            "Не удалось импортировать Django. Убедитесь, что виртуальное окружение активировано и зависимости установлены."
        ) from exc

    # Передаем Django все аргументы командной строки, например runserver или migrate.
    execute_from_command_line(sys.argv)


# Проверяем, что файл запущен напрямую, а не импортирован как модуль.
if __name__ == '__main__':
    # Запускаем главную функцию проекта.
    main()